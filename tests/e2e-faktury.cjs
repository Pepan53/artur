// E2E etapa 1 (demo režim): adresář, faktury, číslování, PDF, úhrady, storno, role.
const { chromium } = require('playwright');
const fs = require('fs');
const { execSync } = require('child_process');
const URL = process.env.URL || 'http://localhost:8765/index.html?demo=1';
const SHOT = process.env.SHOT || '/tmp/shots';
fs.mkdirSync(SHOT, { recursive: true });
(async () => {
  const browser = await chromium.launch();
  const context = await browser.newContext({ viewport: { width: 1300, height: 900 }, acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('dialog', (d) => d.accept());
  const ok = (c, m) => { if (!c) throw new Error('SELHALO: ' + m); console.log('  ✓', m); };
  const step = (s) => console.log('▶', s);
  const nav = async (l) => { if (!(await page.isVisible(`nav.side button:has-text(\"${l}\")`))) await page.click('#nav-nastaveni'); await page.click(`nav.side button:has-text(\"${l}\")`); await page.waitForTimeout(200); };
  const text = () => page.textContent('#app');
  const login = async (e) => { await page.fill('input[name=email]', e); await page.click('button:has-text("Přihlásit")'); await page.waitForTimeout(300); };
  const setPw = async (pw) => { await page.fill('input[name=p1]', pw); await page.fill('input[name=p2]', pw); await page.click('button.primary'); await page.waitForSelector('header.top', { timeout: 15000 }); };
  const unlock = async (pw) => { await page.fill('input[name=pw]', pw); await page.click('button:has-text("Odemknout")'); await page.waitForSelector('header.top', { timeout: 15000 }); };
  const logout = async () => { await page.click('#btn-out'); await page.waitForSelector('#f-login'); };

  await page.goto(URL);
  step('Příprava: Josef, POSTME, Štěpán jako čtenář');
  await login('josef.dvorak@postme.cz'); await setPw('Josef-heslo-2026!');
  await nav('Uživatelé aplikace');
  await page.fill('#f-allow input[name=email]', 'stepan.dvorak@postme.cz'); await page.click('#f-allow button'); await page.waitForTimeout(200);
  await nav('Nový subjekt');
  await page.fill('#f-new input[name=ico]', '09474595'); await page.fill('#f-new input[name=label]', 'POSTME s.r.o.');
  await page.click('#btn-mem-add'); await page.locator('#mem .row').nth(1).locator('input').fill('stepan.dvorak@postme.cz'); await page.locator('#mem .row').nth(1).locator('select').selectOption('ctenar');
  await page.click('#f-new button.primary'); await page.waitForTimeout(400);
  await page.fill('input[name=ulice]', 'Želeč 53'); await page.fill('input[name=psc]', '391 74'); await page.fill('input[name=obec]', 'Želeč');
  await page.fill('input[name=email]', 'info@postme.cz'); await page.fill('input[name=acc_cislo]', '732627175/5500');
  await page.fill('input[name=uvodText]', 'Na základě uzavřené smlouvy Vám fakturujeme následující služby:');
  await page.fill('input[name=posledniCislo]', '63');
  await page.click('#f-subj button.primary');
  await page.waitForSelector('#rk-code'); const key = (await page.textContent('#rk-code')).trim().split('-');
  await page.fill('input[name=g1]', key[1]); await page.fill('input[name=g2]', key[key.length - 2]); await page.click('button:has-text("Potvrzuji")'); await page.waitForTimeout(300);

  step('Adresář');
  await nav('Adresář'); await page.click('#btn-new-zak');
  await page.fill('#f-zak input[name=ico]', '04787625'); await page.fill('#f-zak input[name=nazev]', 'PLOTY OD OTY s.r.o.');
  await page.fill('#f-zak input[name=dic]', 'CZ04787625'); await page.fill('#f-zak input[name=ulice]', 'Lom 64'); await page.fill('#f-zak input[name=psc]', '390 02'); await page.fill('#f-zak input[name=obec]', 'Lom');
  await page.fill('#f-zak input[name=emaily]', 'info@plotyodoty.cz'); await page.fill('#f-zak input[name=splatnost]', '30');
  await page.click('#f-zak button.primary'); await page.waitForTimeout(400);
  ok((await text()).includes('Uloženo: PLOTY OD OTY'), 'zákazník uložen');
  await nav('Adresář'); await page.click('#btn-new-zak');
  await page.fill('#f-zak input[name=nazev]', 'Společenství vlastníků jednotek domu 571'); await page.fill('#f-zak input[name=ico]', '26053403');
  await page.fill('#f-zak input[name=ulice]', 'Vajgar 572'); await page.fill('#f-zak input[name=psc]', '377 01'); await page.fill('#f-zak input[name=obec]', 'Jindřichův Hradec');
  await page.click('#f-zak button.primary'); await page.waitForTimeout(400);
  await nav('Adresář'); await page.click('#btn-new-zak'); await page.fill('#f-zak input[name=ico]', '04787625'); await page.fill('#f-zak input[name=nazev]', 'Duplicita'); await page.click('#f-zak button.primary'); await page.waitForTimeout(300);
  ok(!(await text()).includes('Uloženo: Duplicita'), 'duplicitní IČO odmítnuto');
  await nav('Adresář');
  ok((await page.$$('tr[data-id]')).length === 2, 'adresář má 2 zákazníky');
  await page.screenshot({ path: SHOT + '/11-adresar.png' });

  step('Nová faktura → koncept');
  await nav('Faktury'); await page.click('#btn-new-fa');
  await page.selectOption('select[name=zakaznikId]', { label: 'PLOTY OD OTY s.r.o. · IČO 04787625 · Lom' });
  ok(await page.inputValue('input[name=splatnostDni]') === '30', 'splatnost převzata od zákazníka');
  ok(await page.inputValue('input[name=uvod]') === 'Na základě uzavřené smlouvy Vám fakturujeme následující služby:', 'úvodní text převzat ze subjektu');
  await page.fill('#items tr:nth-child(1) [name=popis]', 'Správa internetových stránek za listopad 2026'); await page.fill('#items tr:nth-child(1) [name=cena]', '20000');
  await page.click('#btn-add');
  await page.fill('#items tr:nth-child(2) [name=popis]', 'Marketingové služby a propagace za listopad 2026'); await page.fill('#items tr:nth-child(2) [name=mnozstvi]', '2'); await page.fill('#items tr:nth-child(2) [name=cena]', '10000');
  await page.waitForTimeout(100);
  ok((await page.textContent('#total')) === '40 000,00 Kč', 'součet 40 000 Kč');
  ok((await page.textContent('#next-no')).includes('20260064'), 'navržené číslo 20260064 (navazuje na 63)');
  await page.screenshot({ path: SHOT + '/12-editor.png', fullPage: true });
  await page.click('button[value=ulozit]'); await page.waitForTimeout(500);
  ok((await text()).includes('Koncept uložen'), 'koncept uložen');
  step('Vystavení');
  await page.click('button[value=vystavit]'); await page.waitForTimeout(600);
  ok((await text()).includes('Vystavena faktura 20260064'), 'faktura 20260064 vystavena');
  await page.screenshot({ path: SHOT + '/13-detail.png', fullPage: true });

  step('PDF');
  const [dl] = await Promise.all([page.waitForEvent('download'), page.click('#btn-pdf')]);
  const pdfPath = SHOT + '/faktura.pdf'; await dl.saveAs(pdfPath);
  const head = fs.readFileSync(pdfPath).subarray(0, 4).toString();
  ok(head === '%PDF', 'PDF vytvořeno (' + dl.suggestedFilename() + ')');
  const t = execSync(`pdftotext -layout "${pdfPath}" -`).toString();
  for (const w of ['Faktura č. 20260064', 'Neplátce DPH', 'PLOTY OD OTY s.r.o.', 'Želeč 53', 'Marketingové služby a propagace', '40 000,00 Kč', '732627175/5500', 'CZ4755000000000732627175', '30.11.2026'.slice(0, 0) || 'DATUM SPLATNOSTI']) ok(t.includes(w), `PDF obsahuje „${w}“`);
  execSync(`pdftoppm -png -r 70 -f 1 -l 1 "${pdfPath}" ${SHOT}/14-pdf`);

  step('Úhrady');
  await page.click('#btn-pay'); await page.fill('#f-pay [name=castka]', '35000'); await page.click('#f-pay button.primary'); await page.waitForTimeout(500);
  ok((await text()).includes('Částečně uhrazená'), 'částečná úhrada → částečně uhrazená');
  await page.click('#btn-pay'); ok(await page.inputValue('#f-pay [name=castka]') === '5000', 'zbývá 5 000 Kč'); await page.click('#f-pay button.primary'); await page.waitForTimeout(500);
  ok((await text()).includes('Stav: Uhrazená'), 'doplatek → uhrazená');

  step('Duplikát a storno');
  await page.click('#btn-dup'); await page.waitForTimeout(300);
  ok((await page.inputValue('#items tr:nth-child(2) [name=popis]')).includes('Marketingové'), 'duplikát převzal položky');
  await page.click('button[value=vystavit]'); await page.waitForTimeout(600);
  ok((await text()).includes('Vystavena faktura 20260065'), 'další číslo 20260065');
  await page.click('#btn-storno'); await page.waitForTimeout(700);
  ok((await text()).includes('stornována dokladem OD20260001'), 'storno vytvořilo OD20260001');
  const [dl2] = await Promise.all([page.waitForEvent('download'), page.click('#btn-pdf')]);
  await dl2.saveAs(SHOT + '/opravny.pdf');
  ok(execSync(`pdftotext -layout ${SHOT}/opravny.pdf -`).toString().includes('-40 000,00 Kč'), 'opravný doklad je záporný');
  await nav('Faktury');
  const t2 = await text();
  ok(t2.includes('Stornovaná') && t2.includes('Uhrazená'), 'seznam ukazuje stavy');
  ok(t2.includes('Vyfakturováno40 000,00 Kč'), 'součet: storno a opravný doklad se vyruší (40 000 Kč)');
  await page.selectOption('#f-stav', 'neuhrazene'); await page.waitForTimeout(200);
  ok((await page.$$('tr[data-fa]')).length === 0, 'filtr neuhrazené je prázdný');
  await page.selectOption('#f-stav', ''); await page.waitForTimeout(200);
  await page.screenshot({ path: SHOT + '/15-seznam.png', fullPage: true });
  await nav('Členové a přístup'); await logout();

  step('Čtenář');
  await login('stepan.dvorak@postme.cz'); await setPw('Stepan-heslo-2026'); await logout();
  await login('josef.dvorak@postme.cz'); await unlock('Josef-heslo-2026!');
  await nav('Členové a přístup'); await page.click('[data-grant]'); await page.waitForTimeout(500); await logout();
  await login('stepan.dvorak@postme.cz'); await unlock('Stepan-heslo-2026');
  await nav('Faktury');
  ok((await page.$$('tr[data-fa]')).length === 3, 'čtenář vidí 3 doklady');
  ok(!(await page.$('#btn-new-fa')), 'čtenář nemá „Nová faktura“');
  await page.click('tr[data-fa] >> nth=0'); await page.waitForTimeout(300);
  ok(!(await page.$('#btn-storno')) && !(await page.$('#btn-pay')), 'čtenář nemůže stornovat ani hradit');

  step('Úložiště bez čitelných dat');
  const raw = await page.evaluate(() => localStorage.getItem('artur-demo-db'));
  for (const w of ['PLOTY', '04787625', 'Marketingové', '40000', 'plotyodoty']) ok(!raw.includes(w), `„${w}“ není v úložišti čitelně`);
  step('Mobil');
  await page.setViewportSize({ width: 390, height: 800 }); await nav('Faktury');
  await page.screenshot({ path: SHOT + '/16-mobil.png', fullPage: true });
  ok(!(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)), 'na mobilu bez vodorovného posunu stránky');
  ok(errors.length === 0, 'žádné chyby v konzoli ' + errors.join(' | '));
  await browser.close();
  console.log('\nE2E FAKTURY OK');
})().catch((e) => { console.error(e); process.exit(1); });
