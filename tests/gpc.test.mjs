import assert from 'node:assert/strict';
import fs from 'node:fs';
import { parseGpc, sparuj, klicPohybu } from '../js/gpc.js';
const dir = process.env.GPC || '/mnt/user-data/uploads/FAKTUR/Banka';
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.gpc')).sort();
const vypisy = files.flatMap((f) => parseGpc(fs.readFileSync(dir + '/' + f).buffer));
assert.equal(vypisy.length, 4);
for (const v of vypisy) assert.ok(v.v_poradku, `výpis ${v.cislo} sedí na obraty a zůstatky`);
assert.equal(vypisy[0].ucet, '732627175'); assert.equal(vypisy[0].nazev, 'POSTME s.r.o.');
assert.equal(vypisy[0].zustatekPredchozi, 48065.6); assert.equal(vypisy[3].zustatek, 49093.03);
const pohyby = vypisy.flatMap((v) => v.pohyby);
assert.equal(pohyby.length, 143); assert.equal(pohyby.filter((p) => p.smer === 'prijem').length, 83);
assert.equal(new Set(pohyby.map(klicPohybu)).size, 143, 'klíče pohybů jsou jedinečné');
const p1 = pohyby.find((p) => p.vs === '20250006');
assert.equal(p1.protiucet, '712521349/0800'); assert.equal(p1.ks, '308'); assert.equal(p1.datum, '2025-01-02');
assert.ok(pohyby.find((p) => p.zprava.includes('Měsíční mzda Martina Dvořáková')), 'zpráva z 078 v češtině (cp1250)');
// párování proti převzatým fakturám POSTME
const mig = JSON.parse(fs.readFileSync(process.env.MIG || '/mnt/user-data/outputs/Migrace/ARTUR-migrace-POSTME.json', 'utf8'));
const faktury = mig.faktury.map((f, i) => ({ ...f, id: 'f' + i, zakaznikId: f.zakaznikKlic, uhrady: [] }));
const r = sparuj(pohyby, faktury, []);
console.log('auto', r.auto.length, 'návrhy', r.navrhy.length, 'nespárované', r.nesparovane.length);
for (const p of r.nesparovane) console.log('   nesp.', p.datum, p.castka, 'VS', p.vs, p.protiucet, (p.text || p.zprava).slice(0, 30));
for (const n of r.navrhy) console.log('   návrh', n.p.datum, n.p.castka, n.f.cislo, n.duvod);
assert.ok(r.auto.length >= 76, 'většina příjmů spárovaná automaticky');
const fa = (c) => faktury.find((f) => f.cislo === c);
const pl = r.auto.filter((a) => a.f.cislo === '20250001');
assert.equal(pl.length, 5, 'faktura 20250001 placená 5 splátkami'); assert.equal(pl.reduce((s, a) => s + a.p.castka, 0), 40000);
assert.ok(r.auto.some((a) => a.f.cislo === '20240116'), 'úhrada faktury z roku 2024 spárována');
console.log('GPC: VŠECHNY TESTY OK');
