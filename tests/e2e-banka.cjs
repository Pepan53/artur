// E2E etapa 4 (demo): výpisy GPC POSTME 01–04/2025 + převzaté faktury POSTME → párování.
const { chromium } = require('playwright');
const URL = process.env.URL || 'http://localhost:8765/index.html?demo=1';
const MIG = process.env.MIG || '/tmp/mig'; const GPC = process.env.GPC || '/tmp/gpc';
const fs = require('fs');
(async () => {
  const browser = await chromium.launch();
  const page = await (await browser.newContext({ viewport: { width: 1300, height: 900 } })).newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(e.message)); page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('dialog', (d) => d.accept());
  const ok = (c, m) => { if (!c) throw new Error('SELHALO: ' + m); console.log('  ✓', m); };
  const nav = async (l) => { await page.click(`nav.side button:has-text("${l}")`); await page.waitForTimeout(400); };
  const text = () => page.textContent('#app');
  await page.goto(URL);
  await page.fill('input[name=email]', 'josef.dvorak@postme.cz'); await page.click('button:has-text("Přihlásit")'); await page.waitForTimeout(300);
  await page.fill('input[name=p1]', 'Josef-heslo-2026!'); await page.fill('input[name=p2]', 'Josef-heslo-2026!'); await page.click('button.primary'); await page.waitForSelector('header.top');
  await page.click('nav.side button:has-text("Nový subjekt")'); await page.fill('#f-new input[name=ico]', '09474595'); await page.fill('#f-new input[name=label]', 'POSTME s.r.o.'); await page.click('#f-new button.primary'); await page.waitForTimeout(400);
  await page.fill('input[name=acc_cislo]', '732627175/5500'); await page.click('#f-subj button.primary');
  await page.waitForSelector('#rk-code'); const k = (await page.textContent('#rk-code')).trim().split('-');
  await page.fill('input[name=g1]', k[1]); await page.fill('input[name=g2]', k[k.length - 2]); await page.click('button:has-text("Potvrzuji")'); await page.waitForTimeout(300);
  await nav('Import z vyfakturuj.cz'); await page.setInputFiles('#file', MIG + '/postme.json'); await page.waitForTimeout(800);
  await page.click('#btn-import'); await page.waitForSelector('text=Import hotov', { timeout: 120000 });
  console.log('▶ Nahrání výpisů');
  await nav('Banka a úhrady');
  const files = fs.readdirSync(GPC).map((f) => GPC + '/' + f);
  await page.setInputFiles('#gpc', files); await page.waitForTimeout(1500);
  const t = await text();
  ok((t.match(/obraty a zůstatky sedí/g) || []).length === 4, '4 výpisy, obraty a zůstatky sedí');
  ok(t.includes('Nových pohybů: 143'), '143 nových pohybů');
  ok(t.includes('Spárováno automaticky podle VS: 79'), '79 úhrad spárováno automaticky');
  ok(t.includes('Nespárované příjmy: 4'), '4 nespárované příjmy');
  await page.screenshot({ path: '/tmp/shots/31-banka-nahled.png', fullPage: true });
  await page.click('#btn-ulozit'); await page.waitForSelector('text=Výpisy uloženy', { timeout: 60000 });
  ok((await page.$$('[data-ign]')).length === 4, 'seznam 4 nespárovaných příjmů');
  await page.click('[data-ign] >> nth=0'); await page.waitForTimeout(800);
  ok((await page.$$('[data-ign]')).length === 3, 'označení „není úhrada faktury“');
  await page.screenshot({ path: '/tmp/shots/32-banka.png', fullPage: true });
  console.log('▶ Opakované nahrání');
  await page.setInputFiles('#gpc', files); await page.waitForTimeout(1500);
  ok((await text()).includes('Žádné nové pohyby'), 'stejné výpisy podruhé nic nezdvojí');
  console.log('▶ Faktury po spárování');
  await nav('Faktury'); await page.selectOption('#f-rok', ''); await page.fill('#q', '20250001'); await page.waitForTimeout(600);
  await page.click('tr[data-fa] >> nth=0'); await page.waitForTimeout(400);
  const d = await text();
  ok(d.includes('Uhrazená') && (d.match(/výpis/g) || []).length >= 5, 'faktura 20250001: 5 splátek z výpisu, uhrazená');
  await nav('Faktury'); await page.selectOption('#f-rok', '2025'); await page.selectOption('#f-stav', 'zaplacena'); await page.fill('#q', ''); await page.waitForTimeout(800);
  const n = (await page.$$('tr[data-fa]')).length; ok(n >= 55, `${n} faktur z roku 2025 je uhrazených`);
  await nav('Adresář'); await page.fill('#q', 'PLOTY'); await page.waitForTimeout(500); await page.click('tr[data-id] >> nth=0'); await page.waitForTimeout(300);
  ok((await page.inputValue('#f-zak input[name=ucty]')).includes('2112621062/2700'), 'účet zákazníka se naučil z výpisu');
  ok(errors.length === 0, 'žádné chyby v konzoli ' + errors.join(' | '));
  await browser.close(); console.log('\nE2E BANKA OK');
})().catch((e) => { console.error(e); process.exit(1); });
