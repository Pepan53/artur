// E2E etapa 3 (demo): oprava faktur, šablony z návrhu, měsíční fakturace, hromadné vystavení, odeslání.
const { chromium } = require('playwright');
const URL = process.env.URL || 'http://localhost:8765/index.html?demo=1';
const DIR = process.env.MIG || '/tmp/mig';
(async () => {
  const browser = await chromium.launch();
  const page = await (await browser.newContext({ viewport: { width: 1300, height: 900 } })).newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(e.message)); page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('dialog', (d) => d.accept());
  const ok = (c, m) => { if (!c) throw new Error('SELHALO: ' + m); console.log('  ✓', m); };
  const nav = async (l) => { if (!(await page.isVisible(`nav.side button:has-text(\"${l}\")`))) await page.click('#nav-nastaveni'); await page.click(`nav.side button:has-text(\"${l}\")`); await page.waitForTimeout(250); };
  const text = () => page.textContent('#app');
  await page.goto(URL);
  await page.fill('input[name=email]', 'josef.dvorak@postme.cz'); await page.click('button:has-text("Přihlásit")'); await page.waitForTimeout(300);
  await page.fill('input[name=p1]', 'Josef-heslo-2026!'); await page.fill('input[name=p2]', 'Josef-heslo-2026!'); await page.click('button.primary'); await page.waitForSelector('header.top');
  await nav('Nový subjekt'); await page.fill('#f-new input[name=label]', 'Karolína Dvořáková'); await page.click('#f-new button.primary'); await page.waitForTimeout(400);
  await page.fill('input[name=acc_cislo]', '732627175/5500'); await page.click('#f-subj button.primary');
  await page.waitForSelector('#rk-code'); const k = (await page.textContent('#rk-code')).trim().split('-');
  await page.fill('input[name=g1]', k[1]); await page.fill('input[name=g2]', k[k.length - 2]); await page.click('button:has-text("Potvrzuji")'); await page.waitForTimeout(300);
  await nav('Import z vyfakturuj.cz'); await page.setInputFiles('#file', DIR + '/karolina.json'); await page.waitForTimeout(500);
  await page.click('#btn-import'); await page.waitForSelector('text=Import hotov');

  console.log('▶ Oprava převzaté faktury');
  await page.fill('#q', '20260066'); await page.waitForTimeout(500);
  await page.click('tr[data-fa] >> nth=0'); await page.waitForTimeout(300);
  await page.click('#btn-edit-prev');
  await page.fill('#pitems tr:nth-child(1) [name=cena]', '1234'); await page.click('#f-prev button.primary'); await page.waitForTimeout(500);
  ok((await text()).includes('Faktura 20260066 opravena') && (await text()).includes('1 234,00 Kč'), 'převzatá faktura opravena');
  ok((await text()).includes('oprava faktury: částka'), 'oprava je v historii faktury');

  console.log('▶ Šablony z návrhu');
  await nav('Opakované faktury'); await page.click('#btn-navrh'); await page.waitForTimeout(300);
  const nav1 = await page.$$('#navrh input[data-i]'); ok(nav1.length >= 3, `navrženo ${nav1.length} šablon`);
  await page.screenshot({ path: '/tmp/shots/21-navrh.png', fullPage: true });
  await page.click('#btn-vytvor'); await page.waitForTimeout(600);
  const pocetSab = (await page.$$('tr[data-id]')).length; ok(pocetSab === nav1.length || pocetSab > 0, `vytvořeno ${pocetSab} šablon`);
  await page.click('tr[data-id] >> nth=0'); await page.waitForTimeout(300);
  ok((await page.textContent('#nahled')).includes('Nejbližší faktura'), 'šablona ukazuje náhled nejbližší faktury');
  await page.screenshot({ path: '/tmp/shots/22-sablona.png', fullPage: true });

  console.log('▶ Měsíční fakturace 12/2026');
  await nav('Měsíční fakturace'); await page.fill('#mesic', '2026-12'); await page.dispatchEvent('#mesic', 'change'); await page.waitForTimeout(400);
  const k1 = (await page.$$('.c1')).length; ok(k1 >= 3, `k vytvoření ${k1} šablon`);
  await page.click('#btn-koncepty'); await page.waitForTimeout(800);
  ok((await page.$$('.c2')).length === k1, 'vznikly koncepty');
  ok((await page.textContent('#app')).includes('listopad 2026'), 'položky mají doplněný měsíc (listopad 2026)');
  await page.screenshot({ path: '/tmp/shots/23-mesic.png', fullPage: true });
  await page.click('#btn-vystavit'); await page.waitForTimeout(1200);
  ok((await text()).includes(`Vystaveno ${k1} faktur (20260067`), 'hromadně vystaveno od 20260067');
  ok((await page.$$('.c1')).length === 0 && (await page.$$('.c2')).length === 0, 'nic nezůstalo k vytvoření ani vystavení');
  ok((await text()).includes('chybí e-mail') && (await page.$$('.c3')).length === 0, 'bez e-mailů nelze odeslat, upozornění');
  const jmeno = (await page.textContent('section.box:nth-of-type(3) tbody tr:nth-child(2) td:nth-child(3)')).trim();
  console.log('    jméno:', jmeno); await nav('Adresář'); await page.fill('#q', jmeno.slice(0, 25)); await page.waitForTimeout(500); await page.click('tr[data-id] >> nth=0');
  await page.fill('#f-zak input[name=emaily]', 'vybor@svj.cz'); await page.click('#f-zak button.primary'); await page.waitForTimeout(400);
  await nav('Měsíční fakturace'); await page.waitForTimeout(300);
  const k3 = (await page.$$('.c3')).length; ok(k3 >= 1, `k odeslání ${k3} faktur s e-mailem`);
  await page.click('#btn-odeslat'); await page.waitForTimeout(1500);
  ok((await text()).includes(`Odesláno ${k3} faktur`), 'odesláno e-mailem');
  const box = JSON.parse(await page.evaluate(() => localStorage.getItem('artur-demo-outbox')));
  ok(box.length === k3 && box[0].to[0] === 'vybor@svj.cz' && box[0].attachment.endsWith('.pdf') && box[0].text.includes('Platbu prosím'), 'e-mail má adresáta, text a PDF přílohu');
  await page.screenshot({ path: '/tmp/shots/24-odeslano.png', fullPage: true });

  console.log('▶ Oprava faktury vystavené ARTURem + odeslání z detailu');
  await page.click('[data-open] >> nth=0'); await page.waitForTimeout(300);
  await page.click('#btn-edit-prev'); await page.fill('#f-prev [name=poznamka]', 'Opraveno'); await page.click('#f-prev button.primary'); await page.waitForTimeout(500);
  ok((await text()).includes('opravena'), 'faktura vystavená ARTURem opravena');
  await page.click('#btn-mail'); await page.waitForTimeout(400);
  await page.fill('#mail-box [name=to]', 'test@example.cz'); await page.click('#btn-send'); await page.waitForTimeout(800);
  ok((await text()).includes('odeslána na test@example.cz'), 'odeslání z detailu faktury');
  console.log('▶ Sloučení POSTME s chybným IČO');
  await nav('Adresář'); await page.fill('#q', '49033727'); await page.waitForTimeout(500);
  await page.click('tr[data-id] >> nth=0'); await page.waitForTimeout(300);
  await page.click('#btn-merge'); await page.waitForTimeout(200);
  const opt = await page.$eval('#merge-to', (s) => s.options[s.selectedIndex].text); ok(opt.includes('09474595'), 'předvybrán POSTME se správným IČO: ' + opt);
  await page.click('#merge-go'); await page.waitForTimeout(800);
  console.log('    ', (await text()).match(/Sloučeno[^.]*./)?.[0]);
  ok(/Sloučeno: \d+ faktur/.test(await text()), 'faktury převedeny na správné IČO');
  await nav('Faktury'); await page.selectOption('#f-rok', ''); await page.fill('#q', '49033727'); await page.waitForTimeout(500);
  ok((await page.$$('tr[data-fa]')).length === 0, 'žádná faktura už nemá IČO 49033727');
  ok(errors.length === 0, 'žádné chyby v konzoli ' + errors.join(' | '));
  await browser.close(); console.log('\nE2E OPAKOVÁNÍ OK');
})().catch((e) => { console.error(e); process.exit(1); });
