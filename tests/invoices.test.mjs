import assert from 'node:assert/strict';
import * as I from '../js/invoices.js';
const s = { rada: '{RRRR}{NNNN}', posledniCislo: { 'faktura:2026': 63 } };
assert.equal(I.formatCislo('{RRRR}{NNNN}', 2026, 7), '20260007');
assert.equal(I.formatCislo('ZF{RR}-{NNN}', 2026, 7), 'ZF26-007');
assert.equal(I.poradiZCisla('{RRRR}{NNNN}', 2026, '20260063'), 63);
assert.equal(I.poradiZCisla('{RRRR}{NNNN}', 2026, '20250063'), null);
assert.equal(I.poradiZCisla('OD{RRRR}{NNNN}', 2026, 'OD20260002'), 2);
assert.equal(I.dalsiCislo(s, [], 'faktura', 2026), '20260064', 'pokračuje za číslem z vyfakturuj.cz');
assert.equal(I.dalsiCislo(s, [{ typ: 'faktura', cislo: '20260070' }, { typ: 'faktura', cislo: '20250099' }], 'faktura', 2026), '20260071');
assert.equal(I.dalsiCislo(s, [], 'faktura', 2027), '20270001', 'nový rok začíná od 1');
assert.equal(I.dalsiCislo(s, [], 'opravny', 2026), 'OD20260001');
assert.equal(I.vsZCisla('OD20260001'), '20260001');
assert.equal(I.radkaCelkem({ mnozstvi: 3, cena: 333.333, sleva: 10 }), 900);
assert.equal(I.soucet([{ mnozstvi: 1, cena: 0.1 }, { mnozstvi: 1, cena: 0.2 }]), 0.3);
assert.equal(I.stavPodleUhrad({ stav: 'vystavena', celkem: 40000, uhrady: [{ castka: 35000 }] }), 'castecne');
assert.equal(I.stavPodleUhrad({ stav: 'vystavena', celkem: 40000, uhrady: [{ castka: 35000 }, { castka: 5000 }] }), 'zaplacena');
assert.equal(I.addDays('2026-01-31', 30), '2026-03-02');
assert.ok(I.poSplatnosti({ stav: 'vystavena', datumSplatnosti: '2026-01-01' }, '2026-01-02'));
const q = I.qrPlatba({ iban: 'CZ47 5500 0000 0007 3262 7175', castka: 2750, vs: '20260064', splatnost: '2026-11-30', zprava: 'Faktura 20260064 *Účtování*', prijemce: 'POSTME s.r.o.' });
assert.equal(q, 'SPD*1.0*ACC:CZ4755000000000732627175*AM:2750.00*CC:CZK*DT:20261130*MSG:FAKTURA 20260064 UCTOVANI*RN:POSTME S.R.O.*X-VS:20260064');
assert.equal(I.czk(40000), '40 000,00 Kč');
console.log('FAKTURY: VŠECHNY TESTY OK');
