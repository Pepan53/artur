// E2E (demo): denní výpis č. 146 a pak měsíční za říjen 2026 → stejné platby se nezdvojí, chybějící výpisy se hlídají jen u měsíčních.
const { chromium } = require('playwright');
const URL = process.env.URL || 'http://localhost:8765/index.html?demo=1';
const MIG = process.env.MIG || '/tmp/mig'; const GPC = process.env.GPC || '/tmp/gpc';
const fs = require('fs');
(async () => {
  const browser = await chromium.launch();
  const page = await (await browser.newContext({ viewport: { width: 1300, height: 900 } })).newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(e.message)); page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('dialog', (d) => d.accept());
  const ok = (c, m) => { if (!c) throw new Error('SELHALO: ' + m); console.log('  ✓', m); };
  const nav = async (l) => { if (!(await page.isVisible(`nav.side button:has-text(\"${l}\")`))) await page.click('#nav-nastaveni'); await page.click(`nav.side button:has-text(\"${l}\")`); await page.waitForTimeout(400); };
  const text = () => page.textContent('#app');
  await page.goto(URL);
  await page.fill('input[name=email]', 'josef.dvorak@postme.cz'); await page.click('button:has-text("Přihlásit")'); await page.waitForTimeout(300);
  await page.fill('input[name=p1]', 'Josef-heslo-2026!'); await page.fill('input[name=p2]', 'Josef-heslo-2026!'); await page.click('button.primary'); await page.waitForSelector('header.top');
  if (!(await page.isVisible('nav.side button:has-text("Nový subjekt")'))) await page.click('#nav-nastaveni'); await page.click('nav.side button:has-text("Nový subjekt")'); await page.fill('#f-new input[name=ico]', '09474595'); await page.fill('#f-new input[name=label]', 'POSTME s.r.o.'); await page.click('#f-new button.primary'); await page.waitForTimeout(400);
  await page.fill('input[name=acc_cislo]', '732627175/5500'); await page.click('#f-subj button.primary');
  await page.waitForSelector('#rk-code'); const k = (await page.textContent('#rk-code')).trim().split('-');
  await page.fill('input[name=g1]', k[1]); await page.fill('input[name=g2]', k[k.length - 2]); await page.click('button:has-text("Potvrzuji")'); await page.waitForTimeout(300);
  await nav('Import z vyfakturuj.cz'); await page.setInputFiles('#file', MIG + '/postme.json'); await page.waitForTimeout(800);
  await page.click('#btn-import'); await page.waitForSelector('text=Import hotov', { timeout: 120000 });
  await nav('Banka a úhrady');
  console.log('▶ Denní výpis 20.10.2026 (č. 146)');
  await page.setInputFiles('#gpc', MIG + '/vypis-2026-146.pdf'); await page.waitForSelector('#gpc-prev table', { timeout: 30000 }); await page.waitForTimeout(400);
  let t = await text();
  ok(t.includes('obraty a zůstatky sedí') && t.includes('Nových pohybů: 7'), 'denní: 7 pohybů, obraty sedí');
  const a1 = Number(t.match(/Spárováno automaticky podle VS: (\d+)/)[1]); ok(a1 === 6, `denní: spárováno ${a1} úhrad`);
  await page.click('#btn-ulozit'); await page.waitForSelector('text=Výpisy uloženy', { timeout: 60000 });
  console.log('▶ Měsíční výpis říjen 2026 (č. 10)');
  await page.setInputFiles('#gpc', MIG + '/vypis-2026-10.pdf'); await page.waitForSelector('#gpc-prev table', { timeout: 30000 }); await page.waitForTimeout(400);
  t = await text();
  ok(t.includes('Nových pohybů: 29') && t.includes('už nahraných 7'), 'měsíční: 29 nových, 7 už nahraných z denního');
  ok(t.includes('u 6 úhrad faktur se údaj o výpisu změní na měsíční'), 'náhled: 6 úhrad se přepíše na měsíční výpis');
  await page.click('#btn-ulozit'); await page.waitForSelector('text=Výpisy uloženy', { timeout: 60000 });
  t = await text();
  ok(!t.includes('Chybí výpisy: 732627175 / 2026 č. 11') && !/č\. 145/.test(t), 'denní výpis nehlásí chybějící č. 11–145');
  ok(t.includes('průběžný · PDF') && t.includes('měsíční · PDF'), 'v seznamu je rozlišen průběžný a měsíční výpis');
  console.log('▶ Faktura 20260186 má jednu úhradu');
  await nav('Faktury'); await page.selectOption('#f-rok', ''); await page.fill('#q', '20260186'); await page.waitForTimeout(600);
  await page.click('tr[data-fa] >> nth=0'); await page.waitForTimeout(400);
  const d = await text();
  ok((d.match(/výpis · výpis č\. 10\/2026 \(PDF\)/g) || []).length === 1, 'úhrada jen jednou a s údajem o měsíčním výpisu č. 10');
  ok(d.includes('výpis č. 146/2026 (PDF) → výpis č. 10/2026 (PDF)'), 'v historii je změna z průběžného na měsíční výpis');
  console.log('▶ Průběžný výpis znovu po měsíčním');
  await nav('Banka a úhrady'); await page.setInputFiles('#gpc', MIG + '/vypis-2026-146.pdf'); await page.waitForSelector('#gpc-prev table', { timeout: 30000 }); await page.waitForTimeout(400);
  ok((await text()).includes('Žádné nové pohyby'), 'průběžný po měsíčním: nic nového, měsíční údaj zůstává');
  ok(d.includes('Uhrazená'), 'faktura uhrazená');
  ok(errors.length === 0, 'žádné chyby v konzoli ' + errors.join(' | '));
  await browser.close(); console.log('\nE2E DENNI OK');
})().catch((e) => { console.error(e); process.exit(1); });
