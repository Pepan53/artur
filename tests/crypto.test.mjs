import * as C from '../js/crypto.js';
import { parseAccount, ibanFromAccount, icoValid } from '../js/czech.js';
import assert from 'node:assert/strict';
const t0=Date.now();
const a = await C.createUserKeys('heslo-josef-123');
const b = await C.createUserKeys('heslo-karolina-1');
console.log('keys', Date.now()-t0,'ms');
const pa = await C.unlockUserKeys(a.stored,'heslo-josef-123');
await assert.rejects(C.unlockUserKeys(a.stored,'spatne-heslo-xx'), /Nesprávné/);
const dek = await C.newSubjectKey();
const wa = await C.wrapForUser(dek, a.stored.publicKey), wb = await C.wrapForUser(dek, b.stored.publicKey);
assert.equal(wa.fp, a.stored.fp);
const sealed = await C.sealJson(dek, {nazev:'POSTME s.r.o.', ico:'09474595'}, 'subject:S1');
const d1 = await C.unwrapForMe(wa.wrapped, pa);
const d2 = await C.unwrapForMe(wb.wrapped, b.privateKey);
assert.deepEqual(await C.openJson(d1, sealed,'subject:S1'), {nazev:'POSTME s.r.o.', ico:'09474595'});
assert.equal((await C.openJson(d2, sealed,'subject:S1')).ico,'09474595');
await assert.rejects(C.openJson(d1, sealed,'subject:S2')); // AAD binding
await assert.rejects(C.unwrapForMe(wa.wrapped, b.privateKey));
const rk = await C.exportRecoveryKey(dek); console.log('recovery', rk);
const back = await C.importRecoveryKey(rk.toLowerCase());
const kc = await C.makeKeyCheck(dek,'S1'); assert.ok(await C.verifyKeyCheck(back,kc,'S1'));
const typo = rk.slice(0,3)+(rk[3]==='A'?'B':'A')+rk.slice(4);
await assert.rejects(C.importRecoveryKey(typo), /překlep/);
const other = await C.newSubjectKey(); assert.equal(await C.verifyKeyCheck(other,kc,'S1'), false);
const st2 = await C.rewrapPrivateKey(a.stored,'heslo-josef-123','nove-heslo-josef-9');
const pa2 = await C.unlockUserKeys(st2,'nove-heslo-josef-9');
await C.unwrapForMe(wa.wrapped, pa2);
assert.equal(C.checkPasswordStrength('kratke'), 'Heslo musí mít aspoň 12 znaků.');
const acc = parseAccount('732627175/5500'); assert.ok(acc.valid); assert.equal(ibanFromAccount(acc),'CZ4755000000000732627175');
assert.ok(icoValid('09474595')); assert.ok(icoValid('04787625')); assert.ok(!icoValid('09474596'));
assert.ok(!parseAccount('732627176/5500').valid);
console.log('VŠECHNY TESTY OK');
