// E2E etapa 2 (demo): import migračního JSON z vyfakturuj.cz, číslování, opakovaný import.
const { chromium } = require('playwright');
const URL = process.env.URL || 'http://localhost:8765/index.html?demo=1';
const DIR = process.env.MIG || '/tmp/mig'; // soubory přejmenované bez diakritiky (Playwright)
(async () => {
  const browser = await chromium.launch();
  const page = await (await browser.newContext({ viewport: { width: 1300, height: 900 } })).newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(e.message)); page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('dialog', (d) => d.accept());
  const ok = (c, m) => { if (!c) throw new Error('SELHALO: ' + m); console.log('  ✓', m); };
  const nav = async (l) => { if (!(await page.isVisible(`nav.side button:has-text(\"${l}\")`))) await page.click('#nav-nastaveni'); await page.click(`nav.side button:has-text(\"${l}\")`); await page.waitForTimeout(200); };
  const text = () => page.textContent('#app');
  await page.goto(URL);
  await page.fill('input[name=email]', 'josef.dvorak@postme.cz'); await page.click('button:has-text("Přihlásit")'); await page.waitForTimeout(300);
  await page.fill('input[name=p1]', 'Josef-heslo-2026!'); await page.fill('input[name=p2]', 'Josef-heslo-2026!'); await page.click('button.primary'); await page.waitForSelector('header.top');
  const subj = async (ico, name) => {
    await nav('Nový subjekt'); await page.fill('#f-new input[name=ico]', ico); await page.fill('#f-new input[name=label]', name);
    await page.click('#f-new button.primary'); await page.waitForTimeout(400);
    await page.fill('input[name=acc_cislo]', '732627175/5500'); await page.click('#f-subj button.primary');
    await page.waitForSelector('#rk-code'); const k = (await page.textContent('#rk-code')).trim().split('-');
    await page.fill('input[name=g1]', k[1]); await page.fill('input[name=g2]', k[k.length - 2]); await page.click('button:has-text("Potvrzuji")'); await page.waitForTimeout(300);
  };
  await subj('', 'Karolína Dvořáková');
  console.log('▶ Import Karolíny');
  await nav('Import z vyfakturuj.cz');
  await page.setInputFiles('#file', DIR + '/karolina.json'); await page.waitForTimeout(500);
  ok((await text()).includes('259 nových'), 'náhled: 259 nových faktur');
  ok((await text()).includes('7 nových'), 'náhled: 7 nových zákazníků');
  const t0 = Date.now();
  await page.click('#btn-import'); await page.waitForSelector('text=Import hotov', { timeout: 120000 });
  console.log('    import trval', Date.now() - t0, 'ms');
  ok((await text()).includes('Další číslo faktury: 20260067'), 'číslování navazuje: 20260067');
  await page.selectOption('#f-rok', ''); await page.waitForTimeout(300);
  ok((await page.$$('tr[data-fa]')).length === 259, 'seznam má 259 faktur');
  await nav('Adresář'); ok((await page.$$('tr[data-id]')).length === 7, 'adresář má 7 zákazníků');
  console.log('▶ Opakovaný import');
  await nav('Import z vyfakturuj.cz'); await page.setInputFiles('#file', DIR + '/karolina.json'); await page.waitForTimeout(500);
  ok((await text()).includes('0 nových') && (await text()).includes('Není co importovat'), 'podruhé nic nového');
  console.log('▶ Nová faktura po importu');
  await nav('Faktury'); await page.click('#btn-new-fa');
  await page.selectOption('select[name=zakaznikId]', { index: 1 });
  await page.fill('#items tr:nth-child(1) [name=popis]', 'Test'); await page.fill('#items tr:nth-child(1) [name=cena]', '100'); await page.waitForTimeout(100);
  ok((await page.textContent('#next-no')).includes('20260067'), 'nová faktura dostane 20260067');
  console.log('▶ Detail převzaté faktury');
  await nav('Faktury'); await page.selectOption('#f-rok', '2023'); await page.waitForTimeout(200);
  await page.click('tr[data-fa] >> nth=0'); await page.waitForTimeout(300);
  ok((await text()).includes('Převzato z vyfakturuj.cz. Originál:'), 'detail ukazuje odkaz na originál PDF');
  const [dl] = await Promise.all([page.waitForEvent('download'), page.click('#btn-pdf')]);
  ok(dl.suggestedFilename().startsWith('Faktura-2023'), 'PDF převzaté faktury lze vytvořit');
  console.log('▶ Úhrady ze screenshotu');
  require('fs').writeFileSync('/tmp/mig/uhrady.json', JSON.stringify({ artur: 'uhrady-vyfakturuj', subjekt: { nazev: 'Karolína Dvořáková' }, uhrady: [{ cislo: '20220001', datum: '2022-11-20', castka: 1 }, { cislo: '20220002', datum: '2022-11-21' }, { cislo: '19990001', datum: '2022-11-21' }] }));
  await nav('Import z vyfakturuj.cz'); await page.setInputFiles('#file', '/tmp/mig/uhrady.json'); await page.waitForTimeout(500);
  ok((await text()).includes('Zapíše se: 2') && (await text()).includes('19990001') && (await text()).includes('Částka nesedí'), 'náhled úhrad: 2 k zapsání, chybějící a nesedící hlášeny');
  await page.click('#btn-uhrady'); await page.waitForTimeout(800);
  ok((await text()).includes('Zapsáno 2 úhrad'), 'úhrady zapsány');
  await page.selectOption('#f-rok', '2022'); await page.selectOption('#f-stav', 'zaplacena'); await page.waitForTimeout(300);
  ok((await page.$$('tr[data-fa]')).length === 2, '2 faktury z 2022 uhrazené');
  console.log('▶ Špatný subjekt');
  await subj('09474595', 'POSTME s.r.o.');
  await nav('Import z vyfakturuj.cz'); await page.setInputFiles('#file', DIR + '/josef.json'); await page.waitForTimeout(500);
  ok(!(await page.$('#btn-import')), 'soubor jiného IČO odmítnut');
  const raw = await page.evaluate(() => localStorage.getItem('artur-demo-db'));
  ok(!raw.includes('Stavební bytové') && !raw.includes('Hvězdná'), 'importovaná data v úložišti nejsou čitelná');
  console.log('    velikost demo úložiště', Math.round(raw.length / 1024), 'KB');
  ok(errors.length === 0, 'žádné chyby v konzoli ' + errors.join(' | '));
  await browser.close(); console.log('\nE2E IMPORT OK');
})().catch((e) => { console.error(e); process.exit(1); });
